"""
Audit every API route under src/routes/api/. For each route, extract:
- DB functions called (imports from $lib/server/db/shivworks)
- Runtime env vars accessed (runtimeEnv.XXX or process.env.XXX)
- External services touched (clerk, activecampaign, resend, stream, etc.)
- Auth gating (requireAuthenticated / requireEntitled / none)
- Dead-path flag (matches a known-dead pattern)

Writes the report to .planning/architecture/BACKEND-CONNECTION-AUDIT.md.
"""

import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")

ROOT = "E:/dev/clients/outerfields/shivworks-network"
API_DIR = os.path.join(ROOT, "src/routes/api")
OUT = os.path.join(ROOT, ".planning/architecture/BACKEND-CONNECTION-AUDIT.md")

DEAD_PATTERNS = [
    "stripe",  # gone but defensive
]

EXTERNAL_HINTS = {
    "clerk": ["@clerk/", "ClerkClient", "clerkUserId", "clerk-webhook"],
    "activecampaign": ["activecampaign", "applyActiveCampaignTag"],
    "resend": ["resend", "sendWelcomeEmail", "sendSessionSecurityEmail", "sendVipBookingEmail", "sendLivestreamReminderEmail", "sendContentReleaseEmail", "sendUpdateNotificationEmail", "sendImportedMemberOnboardingEmail", "sendClientProgressUpdateEmail"],
    "wc": ["wc-webhook", "verifyWcSignature", "x-wc-webhook"],
    "stream": ["stream", "tus", "CLOUDFLARE_STREAM"],
    "kv": ["getOrSet", "bust(", "kv-cache", "KVNamespace"],
    "d1": ["getDBFromPlatform", "D1Database", "from '$lib/server/d1-compat'"],
}


def collect_routes():
    found = []
    for dirpath, _, filenames in os.walk(API_DIR):
        for f in filenames:
            if f == "+server.ts":
                full = os.path.join(dirpath, f)
                route = (
                    full.replace(ROOT.replace("/", os.sep), "")
                    .replace("\\", "/")
                    .lstrip("/")
                )
                found.append((route, full))
    return sorted(found)


def analyze(file_path):
    with open(file_path, encoding="utf-8") as fh:
        src = fh.read()

    # DB functions imported from db/shivworks
    db_calls = []
    m = re.findall(
        r"import\s*\{([^}]+)\}\s*from\s*['\"]\$lib/server/db/shivworks['\"]", src
    )
    for grp in m:
        for name in grp.split(","):
            name = name.strip()
            if name:
                db_calls.append(name)

    # Runtime env vars referenced
    env_vars = sorted(set(re.findall(r"runtimeEnv\.([A-Z_][A-Z0-9_]*)", src)))
    env_vars += sorted(set(re.findall(r"process\.env\.([A-Z_][A-Z0-9_]*)", src)))
    env_vars = sorted(set(env_vars))

    # External services touched
    externals = []
    for service, hints in EXTERNAL_HINTS.items():
        for h in hints:
            if h in src:
                if service not in externals:
                    externals.append(service)
                break

    # Auth gate
    auth = "none"
    if "requireEntitled" in src:
        auth = "requireEntitled"
    elif "requireAuthenticated" in src or "requireAdmin" in src:
        auth = "requireAuthenticated"
    elif "verifyWcSignature" in src or "verifyClerkSignature" in src or "Stream-Signature" in src or "svix" in src.lower() or "stripeSignature" in src:
        auth = "webhook-hmac"
    elif "locals.user" in src or "locals.auth.isAuthenticated" in src:
        auth = "locals-check"

    # Dead?
    is_dead = any(p in file_path.lower() for p in DEAD_PATTERNS)

    # HTTP methods exported
    methods = sorted(
        set(re.findall(r"export\s+const\s+(GET|POST|PUT|DELETE|PATCH)\s*[:=]", src))
    )

    return {
        "methods": methods or ["?"],
        "auth": auth,
        "db": sorted(set(db_calls)),
        "env": env_vars,
        "externals": sorted(externals),
        "dead": is_dead,
    }


def main():
    routes = collect_routes()
    lines = []
    lines.append("# Backend Connection Audit — 2026-05-30")
    lines.append("")
    lines.append(
        "Auto-generated by `.planning/hub-content/_authoring/audit_backend_connections.py`. "
        "Resolves project-skill WHAT #465."
    )
    lines.append("")
    lines.append(
        "Each route below maps to: HTTP methods exported, auth gate, DB functions called, "
        "runtime env vars required (will 5xx if absent unless env-gated inside helper), "
        "external services touched, and dead-path status."
    )
    lines.append("")

    lines.append("## Summary table")
    lines.append("")
    lines.append("| Route | Methods | Auth | DB calls | Externals | Env vars |")
    lines.append("|---|---|---|---|---|---|")
    for route, full in routes:
        info = analyze(full)
        route_disp = "/api/" + route.split("src/routes/api/", 1)[1].replace(
            "/+server.ts", ""
        )
        db = ", ".join(info["db"]) if info["db"] else "—"
        ext = ", ".join(info["externals"]) if info["externals"] else "—"
        env = ", ".join(info["env"]) if info["env"] else "—"
        flag = " 💀 DEAD" if info["dead"] else ""
        lines.append(
            f"| `{route_disp}`{flag} | {', '.join(info['methods'])} | {info['auth']} | {db} | {ext} | {env} |"
        )

    lines.append("")
    lines.append("## Per-route detail")
    lines.append("")
    for route, full in routes:
        info = analyze(full)
        route_disp = "/api/" + route.split("src/routes/api/", 1)[1].replace(
            "/+server.ts", ""
        )
        lines.append(f"### `{route_disp}`")
        lines.append(f"- **File:** `{route}`")
        lines.append(f"- **Methods:** {', '.join(info['methods'])}")
        lines.append(f"- **Auth gate:** {info['auth']}")
        if info["db"]:
            lines.append(f"- **DB functions:** `{', '.join(info['db'])}`")
        if info["env"]:
            lines.append(f"- **Env vars:** `{', '.join(info['env'])}`")
        if info["externals"]:
            lines.append(f"- **External services:** {', '.join(info['externals'])}")
        if info["dead"]:
            lines.append(f"- ⚠️ **DEAD path** — flagged for deletion")
        lines.append("")

    # Required-secret list rollup
    all_env = set()
    for _, full in routes:
        all_env.update(analyze(full)["env"])
    lines.append("## Aggregate env-var surface")
    lines.append("")
    lines.append(
        "Every runtime env var referenced anywhere under `/api/`. "
        "These are what Infisical's `prod` env needs populated for the routes to function."
    )
    lines.append("")
    for v in sorted(all_env):
        lines.append(f"- `{v}`")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print(f"Wrote {OUT} ({len(routes)} routes audited)")


if __name__ == "__main__":
    main()
