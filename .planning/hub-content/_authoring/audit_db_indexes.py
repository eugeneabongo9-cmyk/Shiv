"""
Audit every CREATE INDEX statement across migrations/*.sql.

For each index, extract:
- Name
- Table
- Columns
- Whether it's UNIQUE
- Source migration

Then grep the codebase for queries that touch the same table and reference
the index's columns in WHERE/JOIN clauses → flag as USED (count + sample
file) or UNUSED (no consumer found).

Writes the report to .planning/architecture/INDEXES-AUDIT.md.
Re-run anytime to refresh.
"""

import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")

ROOT = "E:/dev/clients/outerfields/shivworks-network"
MIG_DIR = os.path.join(ROOT, "migrations")
DB_FILE = os.path.join(ROOT, "src/lib/server/db/shivworks.ts")
SRC_ROOT = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, ".planning/architecture/INDEXES-AUDIT.md")

# Regex captures: name, table, columns
INDEX_RE = re.compile(
    r"CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+(?:\n\s*)?ON\s+(\w+)\s*\(([^)]+)\)",
    re.IGNORECASE,
)


def collect_indexes():
    indexes = []
    for mig in sorted(os.listdir(MIG_DIR)):
        if not mig.endswith(".sql"):
            continue
        path = os.path.join(MIG_DIR, mig)
        with open(path, encoding="utf-8") as fh:
            content = fh.read()
        # Flatten multi-line CREATE INDEX statements
        for m in INDEX_RE.finditer(content):
            unique = bool(m.group(1))
            name = m.group(2)
            table = m.group(3)
            cols_raw = m.group(4)
            cols = [c.strip().split()[0] for c in cols_raw.split(",")]
            indexes.append(
                {
                    "name": name,
                    "table": table,
                    "columns": cols,
                    "unique": unique,
                    "migration": mig,
                }
            )
    return indexes


def find_consumers(table, columns):
    """Return list of (file, snippet) where the table + a column appear together."""
    consumers = []
    # Read the DB module first — most queries live there
    with open(DB_FILE, encoding="utf-8") as fh:
        src = fh.read()

    # Split into lines for context around hits
    lines = src.split("\n")
    for i, line in enumerate(lines):
        if table in line and any(col in line for col in columns):
            consumers.append(("src/lib/server/db/shivworks.ts", line.strip()[:120], i + 1))

    # Also scan src/routes/**/+server.ts and +page.server.ts
    for dirpath, _, filenames in os.walk(SRC_ROOT):
        for f in filenames:
            if not (f.endswith("+server.ts") or f.endswith("+page.server.ts")):
                continue
            full = os.path.join(dirpath, f)
            if full == DB_FILE:
                continue
            try:
                with open(full, encoding="utf-8") as fh:
                    text = fh.read()
            except Exception:
                continue
            if table in text:
                # Coarse check — table name appears. Not necessarily index-relevant.
                rel = full.replace(ROOT.replace("/", os.sep), "").replace(
                    "\\", "/"
                ).lstrip("/")
                consumers.append((rel, f"(references table `{table}`)", 0))

    return consumers


def main():
    indexes = collect_indexes()
    lines = []
    lines.append("# DB Index Audit — 2026-05-30")
    lines.append("")
    lines.append(
        "Auto-generated by `.planning/hub-content/_authoring/audit_db_indexes.py`. "
        "Resolves project-skill WHAT #464."
    )
    lines.append("")
    lines.append(
        "Inventory of every `CREATE INDEX` statement across `migrations/*.sql`, "
        "mapped to query consumers in `src/lib/server/db/shivworks.ts` and route handlers."
    )
    lines.append("")
    lines.append(f"**Total indexes:** {len(indexes)} across {len(set(i['migration'] for i in indexes))} migrations.")
    lines.append("")

    lines.append("## Summary table")
    lines.append("")
    lines.append("| Index | Table | Columns | Unique | Migration | Consumers |")
    lines.append("|---|---|---|---|---|---|")
    for idx in indexes:
        consumers = find_consumers(idx["table"], idx["columns"])
        unique_marker = "✓" if idx["unique"] else ""
        cols = ", ".join(idx["columns"])
        # de-dup consumers by file
        files = sorted(set(c[0] for c in consumers))
        consumer_marker = f"{len(consumers)} ({len(files)} files)" if consumers else "⚠️ none found"
        lines.append(
            f"| `{idx['name']}` | `{idx['table']}` | {cols} | {unique_marker} | `{idx['migration']}` | {consumer_marker} |"
        )

    lines.append("")
    lines.append("## Per-index detail")
    lines.append("")
    for idx in indexes:
        consumers = find_consumers(idx["table"], idx["columns"])
        lines.append(f"### `{idx['name']}`")
        lines.append(f"- **Table:** `{idx['table']}`")
        lines.append(f"- **Columns:** {', '.join(f'`{c}`' for c in idx['columns'])}")
        lines.append(f"- **Unique:** {'yes' if idx['unique'] else 'no'}")
        lines.append(f"- **Migration:** `{idx['migration']}`")
        if consumers:
            lines.append(f"- **Consumers ({len(consumers)} hits):**")
            seen = set()
            for c in consumers[:8]:
                file_key = c[0]
                if file_key in seen:
                    continue
                seen.add(file_key)
                if c[2]:
                    lines.append(f"  - `{c[0]}:{c[2]}` — `{c[1]}`")
                else:
                    lines.append(f"  - `{c[0]}` {c[1]}")
            if len(seen) > 8:
                lines.append(f"  - ...and {len(seen) - 8} more file(s)")
        else:
            lines.append("- ⚠️ **No consumers found** — candidate for removal or worth verifying via EXPLAIN.")
        lines.append("")

    lines.append("## Launch-critical hot paths")
    lines.append("")
    lines.append(
        "The following indexes back the launch-day critical-path queries. "
        "If any of these are missing from the deployed D1 instance, the listed flow degrades."
    )
    lines.append("")
    lines.append("| Flow | Required index | Without it |")
    lines.append("|---|---|---|")
    lines.append("| Member identity resolution by Clerk user ID | `members(clerk_user_id)` (PK implicit) | every authenticated request scans `members` |")
    lines.append("| WC webhook idempotency lookup | `processed_webhook_events (source, event_id)` (PK implicit) | replay protection scans full table |")
    lines.append("| Claim-on-signin by email | `idx_members_email` | every Clerk signup scans `members` |")
    lines.append("| Imported-member provision lookup by email | `idx_member_imports_email` | claim-by-email scans `member_imports` |")
    lines.append("| Dashboard tier-gated content | `idx_members_tier`, `idx_members_access_status` | dashboard load scans `members` |")
    lines.append("| Library episode progress per member | `idx_member_episode_progress_member_episode` | progress reads scan full table per request |")
    lines.append("| Gamification per member | `idx_member_gamification_member_id` | gamification widget scans `member_gamification` |")
    lines.append("")

    lines.append("## Findings")
    lines.append("")
    lines.append(
        "- `migrations/0013_member_profiles_tags.sql` is in the working tree but "
        "may not be on `main` yet — its indexes are included in this audit "
        "but verify before the launch deploy."
    )
    lines.append(
        "- Indexes with `⚠️ no consumers found` in the table above are not "
        "necessarily dead — the scanner only matches table + column name "
        "co-occurrence in TypeScript files. Indexes used in inline SQL fragments "
        "or via raw query strings may be missed. Manual EXPLAIN against the "
        "deployed D1 is the authoritative check."
    )
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"Wrote {OUT} ({len(indexes)} indexes audited)")


if __name__ == "__main__":
    main()
